/**
 * Noir — pixel-exact reproductions of the owner's uploaded label artwork
 * (four raster masters). The artwork ships as a locked full-bleed plate
 * (public/templates/noir/*.png, variable regions healed out) and exactly
 * nine editable objects sit on top at the artwork's own positions:
 * product name, strength, CAT code, LOT / MFG / EXP values, composition,
 * the vertical batch number, and a real Code 128 barcode. Everything
 * else — brand, badge, notices, storage text, QR, frames — IS the
 * artwork and stays identical.
 *
 * Geometry lives in GEOMETRIES, measured in master-PNG pixels and
 * converted at the fixed physical size (60 × 30 mm, the artwork's own
 * 2:1). The numbers were derived by closed-loop calibration: each field
 * was rendered through the real export pipeline and its ink compared
 * against the master's until positions and sizes coincide. The masters
 * are raster (no font data), so overlay text uses the closest bundled
 * faces: Inter 700 for the display text, Archivo Narrow 400 for the
 * condensed data text. Sizes below the house 3.5 pt floor reproduce the
 * artwork's own microtext (templates.test.ts carves this family out).
 */

interface FieldGeom {
  /** Ink-box center in master px. */
  cx: number;
  cy: number;
  /** Text box width in master px (wide enough that seeded text never wraps). */
  w: number;
  /** Font size in points. */
  pt: number;
  /** Line height (multi-line fields). */
  lh?: number;
}

interface Geometry {
  /** Master pixel width (pre-bleed) — sets the px→mm scale. */
  masterPx: number;
  /** Healed plate dimensions (with bleed) for naturalWidthPx/HeightPx. */
  plate: [number, number];
  product: FieldGeom;
  strength: FieldGeom;
  cat: FieldGeom;
  lot: FieldGeom;
  mfg: FieldGeom;
  exp: FieldGeom;
  composition: FieldGeom;
  /** Vertical batch: w = run length along the reading direction. */
  batch: FieldGeom;
  /** Barcode bars: [cx, cy, runPx, barPx] (rotated 90°). */
  barcode: [number, number, number, number];
}

