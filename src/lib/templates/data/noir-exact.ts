interface Skin {
  id: "core" | "cryo" | "spectral" | "grid";
  name: string;
  description: string;
  plateUrl: string;
  background: string;
  productColor: string;
  valueColor: string;
  compositionColor: string;
  strengthColor: string;
  catColor: string;
  batchColor: string;
}

function noirTemplate(skin: Skin): TemplateDef {
  const g = GEOMETRIES[skin.id];
  const S = 60 / g.masterPx;
  const mm = (px: number) => Math.round(px * S * 1000) / 1000;
  const solid = (color: string): Fill => ({ type: "solid", color });

  const field = (
    name: string,
    f: FieldGeom,
    options: {
      color: string;
      textValue: string;
      display?: boolean;
      align?: "left" | "center" | "right";
      lines?: number;
      letterSpacingEm?: number;
      rotationDeg?: number;
    },
  ) => {
    const fontMm = f.pt * 0.3528;
    const lines = options.lines ?? 1;
    const lineHeight = f.lh ?? 1.15;
    return text({
      name,
      text: options.textValue,
      xMm: mm(f.cx),
      yMm: mm(f.cy),
      widthMm: mm(f.w),
      heightMm: Math.round(lines * fontMm * lineHeight * 100) / 100,
      fontSizePt: f.pt,
      fontFamilyId: options.display ? "inter" : "archivo-narrow",
      fontWeight: options.display ? 700 : 400,
      lineHeight,
      letterSpacingEm: options.letterSpacingEm ?? 0,
      align: options.align ?? "center",
      fill: solid(options.color),
      rotationDeg: options.rotationDeg ?? 0,
    });
  };

  return {
    id: `noir-exact-${skin.id}`,
    name: skin.name,
    brand: "NOIR PEPTIDES",
    description: skin.description,
    categories: ["pharma", "lab"],
    premium: false,
    presetId: "10ml-crimp",
    doc: templateDoc("10ml-crimp", {
      label: { style: "partial-wrap", widthMm: 60, heightMm: 30, bleedMm: 2, safeMm: 2 },
      background: { type: "solid", color: skin.background },
      substrateId: "white-pp",
      objects: [
        image({
          name: "Artwork plate (locked)",
          url: skin.plateUrl,
          xMm: 30,
          yMm: 15,
          widthMm: 64,
          heightMm: 34,
          naturalWidthPx: g.plate[0],
          naturalHeightPx: g.plate[1],
        }),
        field("Product name", g.product, {
          color: skin.productColor,
          display: true,
          lines: 2,
          textValue: "CJC-1295 +\nIpamorelin Blend",
        }),
        field("Strength", g.strength, {
          color: skin.strengthColor,
          display: true,
          textValue: "10 mg (5/5)",
        }),
        field("Catalog code", g.cat, {
          color: skin.catColor,
          letterSpacingEm: 0.1,
          textValue: "NP-CJC1295IPAM-10",
        }),
        field("LOT value", g.lot, {
          color: skin.valueColor,
          align: "left",
          textValue: "NP2405-001",
        }),
        field("MFG value", g.mfg, {
          color: skin.valueColor,
          align: "left",
          textValue: "05/24/2024",
        }),
        field("EXP value", g.exp, {
          color: skin.valueColor,
          align: "left",
          textValue: "05/24/2026",
        }),
        field("Composition", g.composition, {
          color: skin.compositionColor,
          align: "left",
          lines: 2,
          textValue: "CJC-1295 (DAC) – 5 mg\nIpamorelin – 5 mg",
        }),
        field("Batch (vertical)", g.batch, {
          color: skin.batchColor,
          rotationDeg: -90,
          textValue: "NP2405-001",
        }),
        barcode({
          name: "Barcode",
          value: "NP2405-001",
          symbology: "code128",
          showText: false,
          bgColor: null,
          fgColor: "#000000",
          xMm: mm(g.barcode[0]),
          yMm: mm(g.barcode[1]),
          widthMm: mm(g.barcode[2]),
          heightMm: mm(g.barcode[3]),
          rotationDeg: 90,
        }),
      ],
    }),
  };
}

